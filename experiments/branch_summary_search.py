"""Do compact summaries determine the zero-word branch? A counterexample search.

At a settled ZERO word the left-diagonal recursion

    D_d(t+1) = D_{d-2}(t) XOR ( D_{d-1}(t) OR D_d(t) )                   (R)

degenerates: with D_{d-1} == 0 on the period the map becomes
D_d(t+1) = D_{d-2}(t) XOR D_d(t), which admits exactly TWO period-p solutions,
complements of one another. Which one occurs is fixed by the transient, and
`experiments/transient_branch_selector.py` found that on the seven seed-reachable
branches the phase of the last reset plus one tail bit picks it out -- while
computing that phase still costs a transient growing like 1.335*d.

This script asks whether any compact summary S of a diagonal's history is a
STATE: whether `S` determines the branch. It is a falsifier, not a fitter. For
each candidate it hunts for a collision -- two histories with identical summary
and different branch -- and prints the counterexample when it finds one.

Two populations, reported separately and never pooled:

  arbitrary   histories generated by running (R) from freely chosen column
              pairs. A collision here refutes the summary as a GENERAL
              recurrence and nothing more: these are not the seed's orbit and
              CLAUDE.md rule 3 applies to any claim about Rule 30 itself.
  seed        branches actually reachable on the single-seed orbit. Few, so
              the power is low, and the count is reported so that "no
              collision" is read as "not many chances", not as evidence.

THE CONTROL THAT MATTERS. A summary with a large range has few repeated values,
so it cannot collide for want of opportunity -- a forced positive in the sense
of docs/theory/README.md §5. Every row therefore carries `n_distinct_summaries`
against `n_events` and `n_colliding_keys`: a summary whose keys are nearly all
unique has not been tested at all, and the verdict says so rather than
reporting a pass.

Usage:
    python experiments/branch_summary_search.py --histories 4000 --pretty
    python experiments/branch_summary_search.py --verify runs/<artifact>.json
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np

ARTIFACT_TYPE = "rule30.branch_summary_search"
ARTIFACT_VERSION = 1
PERIODS = (1, 2, 4, 8, 16, 32)


def step_column(a: np.ndarray, b: np.ndarray, c0: int) -> np.ndarray:
    """Next diagonal from its two predecessors, via (R).

    c[t+1] = a[t] XOR (b[t] OR c[t]); c[0] is free -- it is the cone-edge value
    the caller supplies, and it is exactly the branch degree of freedom.
    """
    n = len(a)
    c = np.zeros(n, dtype=np.uint8)
    c[0] = c0
    for t in range(n - 1):
        c[t + 1] = a[t] ^ (b[t] | c[t])
    return c


def tail_period(col: np.ndarray, tail: int) -> int | None:
    seg = col[-tail:]
    for p in PERIODS:
        if len(seg) > 2 * p and np.array_equal(seg[:-p], seg[p:]):
            return p
    return None


def tail_word(col: np.ndarray, p: int) -> int:
    """The settled p-bit word, phase-locked to t mod p."""
    w = 0
    for t in range(len(col) - p, len(col)):
        w |= int(col[t]) << (t % p)
    return w


def last_reset(col: np.ndarray) -> int:
    """Last t with col[t] == 1, or -1. The 'final reset' of the transient."""
    nz = np.flatnonzero(col)
    return int(nz[-1]) if len(nz) else -1


def settle_time(col: np.ndarray, p: int, tail: int) -> int:
    """Earliest t from which col is exactly p-periodic to the end."""
    n = len(col)
    lo = 0
    for t in range(n - tail, -1, -1):
        if t + p < n and col[t] != col[t + p]:
            lo = t + 1
            break
    return lo


def summaries(u_word: int, zero_col: np.ndarray, p: int, tail: int) -> dict:
    """Candidate summaries of the branch point, cheapest first.

    `u_word` is the settled word of D_{d-2}; `zero_col` is the full history of
    the zero diagonal D_{d-1}, which is what a summary is trying to replace.
    """
    lr = last_reset(zero_col)
    st = settle_time(zero_col, p, tail)
    pc = int(zero_col.sum())
    return {
        "predecessor_word": (u_word,),
        "word+reset_phase": (u_word, lr % p if lr >= 0 else -1),
        "word+reset_phase_2p": (u_word, lr % (2 * p) if lr >= 0 else -1),
        "word+transient_parity": (u_word, pc & 1),
        "word+reset_phase+parity": (u_word, lr % p if lr >= 0 else -1, pc & 1),
        "word+settle_phase": (u_word, st % p),
        "word+tail_boundary_bit": (u_word, int(zero_col[len(zero_col) - p - 1])),
    }


def branch_of(col: np.ndarray, p: int, u_word: int) -> int:
    """0 or 1: which of the two period-p solutions this diagonal settled into.

    The two differ by complement, so the low bit of the settled word names the
    branch once the pair is fixed. `u_word` is carried only to key the event.
    """
    return tail_word(col, p) & 1


def branch_event(u_col: np.ndarray, z_col: np.ndarray, tail: int) -> dict | None:
    """One zero-word branch: the ACTUAL successor, not both hypotheticals.

    The branch is not a free choice. `c0 = D_d(0)` is the cone-edge value, and
    on the seed orbit it is 0 for every d >= 2; the two period-p solutions are
    both legal for (R) in the abstract, but only one is the continuation of a
    given history. An earlier version of this file recorded both and called the
    resulting collision a refutation, which tested nothing -- it had fed the
    same summary two different branches by construction.
    """
    pz = tail_period(z_col, tail)
    pu = tail_period(u_col, tail)
    if pz is None or pu is None or tail_word(z_col, pz) != 0:
        return None
    nxt = step_column(u_col, z_col, 0)
    pn = tail_period(nxt, tail)
    if pn is None:
        return None
    return {
        "summaries": summaries(tail_word(u_col, pu), z_col, max(pz, pu), tail),
        "branch": branch_of(nxt, pn, tail_word(u_col, pu)),
    }


def events_from(a: np.ndarray, b: np.ndarray, depth: int, tail: int) -> list[dict]:
    """Walk (R) forward from a column pair, recording every zero-word branch."""
    out = []
    cols = [a, b]
    for _ in range(2, depth):
        ev = branch_event(cols[-2], cols[-1], tail)
        if ev is not None:
            out.append(ev)
        cols.append(step_column(cols[-2], cols[-1], 0))
    return out


def collide(events: list[dict], name: str) -> dict:
    """Does this summary determine the branch? Counterexample if not."""
    table: dict[tuple, set] = defaultdict(set)
    example: dict[tuple, list] = defaultdict(list)
    for e in events:
        key = e["summaries"][name]
        table[key].add(e["branch"])
        if len(example[key]) < 2:
            example[key].append(e["branch"])
    colliding = [k for k, v in table.items() if len(v) > 1]
    n_events, n_keys = len(events), len(table)
    # Opportunity: how many events share a key with another event at all. A
    # summary whose keys are all unique could not have collided, so a pass
    # says nothing -- this is the forced-positive control, not a statistic.
    counts: dict[tuple, int] = defaultdict(int)
    for e in events:
        counts[e["summaries"][name]] += 1
    repeated = sum(c for c in counts.values() if c > 1)
    return {
        "summary": name,
        "n_events": n_events,
        "n_distinct_summaries": n_keys,
        "n_colliding_keys": len(colliding),
        "events_with_a_twin": repeated,
        "determines_branch": not colliding,
        "counterexample": (
            {"key": list(colliding[0]), "branches": sorted(table[colliding[0]])}
            if colliding else None),
        "tested": repeated > 0,
        "verdict": (
            "REFUTED: same summary, different branch" if colliding
            else "UNTESTED: every summary value is unique, so a collision was "
                 "impossible -- this is a forced pass, not a result"
            if repeated == 0
            else "survived on this population"),
    }


def _settled_column(word: int, p: int, transient: np.ndarray,
                    length: int) -> np.ndarray:
    """A legal diagonal history: an arbitrary transient, then a p-periodic tail.

    Zero words are rare on the seed orbit -- `w_d = 0` iff `w_{d-2} = w_{d-1}`,
    which is a 2^-p event -- so waiting for them to occur naturally buys almost
    no events. They are constructed here instead. Nothing about (R) requires a
    column to be seed-reachable for a GENERAL recurrence to have to handle it,
    which is exactly what this population tests and all it tests.
    """
    col = np.zeros(length, dtype=np.uint8)
    col[:len(transient)] = transient
    for t in range(len(transient), length):
        col[t] = (word >> (t % p)) & 1
    return col


def arbitrary_population(n_histories: int, length: int, depth: int, tail: int,
                         seed: int) -> list[dict]:
    """Constructed (predecessor, zero-word) pairs with varied transients.

    The zero column's TAIL is fixed at 0 by construction; only its transient
    varies. That is the whole question -- whether a summary of the transient
    decides the branch -- put directly, rather than waited for.
    """
    rng = np.random.default_rng(seed)
    events = []
    periods = (4, 8, 16)
    for _ in range(n_histories):
        p = int(rng.choice(periods))
        u_word = int(rng.integers(0, 1 << p))
        tlen = int(rng.integers(1, 3 * p + 1))
        u_col = _settled_column(u_word, p, rng.integers(0, 2, tlen, dtype=np.uint8),
                                length)
        z_len = int(rng.integers(1, 3 * p + 1))
        z_col = _settled_column(0, p, rng.integers(0, 2, z_len, dtype=np.uint8),
                                length)
        ev = branch_event(u_col, z_col, tail)
        if ev is not None:
            events.append(ev)
    return events


def seed_population(steps: int, depth: int, tail: int) -> list[dict]:
    """The real orbit, taken from a direct simulation rather than from (R).

    Using the simulator here rather than iterating step_column makes the seed
    population an INDEPENDENT path to the same columns: if (R) and the rule
    disagreed anywhere, these two populations would diverge instead of both
    being wrong in the same way.
    """
    width = 2 * steps + 3
    centre = steps + 1
    mask = (1 << width) - 1
    wmask = (1 << depth) - 1
    nbytes = (depth + 7) // 8
    cols = np.zeros((steps + 1, depth), dtype=np.uint8)
    state = 1 << centre
    for t in range(steps + 1):
        win = (state >> (centre - t)) & wmask
        cols[t] = np.unpackbits(
            np.frombuffer(win.to_bytes(nbytes, "little"), dtype=np.uint8),
            bitorder="little", count=depth)
        state = ((state << 1) ^ (state | (state >> 1))) & mask
    out = []
    for d in range(2, depth):
        ev = branch_event(cols[:, d - 2], cols[:, d - 1], tail)
        if ev is not None:
            # The actual successor is the simulated column, not a recomputation.
            pn = tail_period(cols[:, d], tail)
            if pn is None:
                continue
            ev["branch"] = branch_of(cols[:, d], pn, 0)
            out.append(ev)
    return out


def run(n_histories: int, length: int, depth: int, tail: int, steps: int,
        seed: int) -> dict:
    started = time.time()
    arb = arbitrary_population(n_histories, length, depth, tail, seed)
    sd = seed_population(steps, depth, tail)
    names = list(summaries(0, np.zeros(64, dtype=np.uint8), 8, tail))
    return {
        "artifact_type": ARTIFACT_TYPE,
        "artifact_version": ARTIFACT_VERSION,
        "params": {"n_histories": n_histories, "length": length,
                   "depth": depth, "tail": tail, "steps": steps, "seed": seed},
        "arbitrary": {"n_events": len(arb),
                      "rows": [collide(arb, n) for n in names]},
        "seed_orbit": {"n_events": len(sd),
                       "rows": [collide(sd, n) for n in names],
                       "note": "single-seed events only; a small count means "
                               "low power, not a clean result"},
        "elapsed_s": round(time.time() - started, 2),
    }


def verify(path: Path) -> int:
    art = json.loads(path.read_text(encoding="utf-8"))
    if art.get("artifact_type") != ARTIFACT_TYPE:
        print(f"not a {ARTIFACT_TYPE} artifact", file=sys.stderr)
        return 2
    p = art["params"]
    fresh = run(p["n_histories"], p["length"], p["depth"], p["tail"],
                p["steps"], p["seed"])
    ok = True
    for pop in ("arbitrary", "seed_orbit"):
        for old, new in zip(art[pop]["rows"], fresh[pop]["rows"]):
            for key in ("n_events", "n_distinct_summaries", "n_colliding_keys",
                        "determines_branch"):
                if old[key] != new[key]:
                    print(f"MISMATCH {pop}/{old['summary']}/{key}: "
                          f"{old[key]} -> {new[key]}", file=sys.stderr)
                    ok = False
    print(f"verify: {'OK' if ok else 'FAILED'}")
    return 0 if ok else 1


def self_test() -> int:
    """(R) must reproduce the simulator, and step_column must be exact."""
    bad = 0
    steps = 200
    width = 2 * steps + 3
    centre = steps + 1
    mask = (1 << width) - 1
    state = 1 << centre
    ref = np.zeros((steps + 1, 12), dtype=np.uint8)
    for t in range(steps + 1):
        win = state >> (centre - t)
        for d in range(12):
            ref[t, d] = (win >> d) & 1
        state = ((state << 1) ^ (state | (state >> 1))) & mask
    cols = [ref[:, 0], ref[:, 1]]
    for d in range(2, 12):
        nxt = step_column(cols[-2], cols[-1], int(ref[0, d]))
        if not np.array_equal(nxt, ref[:, d]):
            print(f"FAIL step_column at d={d}", file=sys.stderr)
            bad += 1
        cols.append(nxt)
    # A zero word really must admit both branches.
    z = np.zeros(64, dtype=np.uint8)
    u = np.zeros(64, dtype=np.uint8)
    c_a, c_b = step_column(u, z, 0), step_column(u, z, 1)
    if np.array_equal(c_a, c_b):
        print("FAIL zero word did not branch", file=sys.stderr)
        bad += 1
    print(f"self-test: {'OK' if not bad else f'{bad} failure(s)'}")
    return 0 if not bad else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--histories", type=int, default=3000)
    ap.add_argument("--length", type=int, default=192)
    ap.add_argument("--depth", type=int, default=24)
    ap.add_argument("--tail", type=int, default=64)
    ap.add_argument("--steps", type=int, default=4096)
    ap.add_argument("--seed", type=int, default=30)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--verify", type=Path)
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--pretty", action="store_true")
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()
    if args.verify:
        return verify(args.verify)

    art = run(args.histories, args.length, args.depth, args.tail,
              args.steps, args.seed)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(art, indent=2) + "\n", encoding="utf-8")
    if args.pretty:
        for pop in ("arbitrary", "seed_orbit"):
            print(f"\n{pop}: {art[pop]['n_events']} branch events",
                  file=sys.stderr)
            print(f"  {'summary':<26} {'keys':>7} {'collide':>8} {'twins':>7}  verdict",
                  file=sys.stderr)
            for r in art[pop]["rows"]:
                print(f"  {r['summary']:<26} {r['n_distinct_summaries']:>7} "
                      f"{r['n_colliding_keys']:>8} {r['events_with_a_twin']:>7}  "
                      f"{r['verdict'][:52]}", file=sys.stderr)
    print(json.dumps(art, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
