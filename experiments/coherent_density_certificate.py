#!/usr/bin/env python3
"""Test the two-update predecessor-coherent density/flux language.

Every temporal edge is generated by one shared seven-bit Rule 30 predecessor
word.  Floating point optimization is used only to find candidates; every
reported obstruction is converted to an integer Farkas identity and checked
exactly.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import itertools
import json
from math import gcd, lcm
from pathlib import Path


BITS = tuple(itertools.product((0, 1), repeat=3))


def update(centre, left, right):
    return centre ^ (left | right)


def coherent_relation():
    """Return the 20 adjacent-row states and 44 shared-predecessor edges."""
    edges = set()
    for u, v, w, z, a, b, c in itertools.product((0, 1), repeat=7):
        first = (a, b, c)
        second = (update(a, z, w), update(b, a, z), update(c, b, a))
        zp, wp = update(z, w, v), update(w, v, u)
        third = (update(second[0], zp, wp), update(second[1], second[0], zp),
                 update(second[2], second[1], second[0]))
        edges.add((first, second, third))
    states = sorted({(a, b) for a, b, _ in edges} | {(b, c) for _, b, c in edges})
    coherent = sorted(((a, b), (b, c)) for a, b, c in edges)
    return states, coherent


def inequality_system(time_parity: bool, alpha: int | None = 8):
    """Build A*x >= rhs for the coherent signed language.

    ``alpha=None`` makes alpha a variable and imposes alpha>=0.  Thus an
    infeasibility witness that cancels the alpha column excludes every finite
    nonnegative slope, including all positive slopes.
    """
    if alpha is not None and (type(alpha) is not int or alpha < 0):
        raise ValueError('alpha must be a nonnegative integer or None')
    states, edges = coherent_relation()
    phases = range(2 if time_parity else 1)
    names = ([('F', p, t, a, b) for p in (0, 1) for t in phases
              for a, b in itertools.product((0, 1), repeat=2)] +
             [('psi', p, t, *r, *rp) for p in (0, 1) for t in phases
              for r, rp in states] +
             [('b', p) for p in (0, 1)] +
             [('g', p, a, b) for p in (0, 1)
              for a, b in itertools.product((0, 1), repeat=2)] +
             [('chi', p, t, a, b) for p in (0, 1) for t in phases
              for a, b in itertools.product((0, 1), repeat=2)] +
             ([('alpha',)] if alpha is None else []))
    indices = {name: j for j, name in enumerate(names)}
    rows, rhs, labels = [], [], []

    def add(terms, bound, label):
        row = [0] * len(names)
        for name, coefficient in terms:
            row[indices[name]] += coefficient
        rows.append(row)
        rhs.append(bound)
        labels.append(label)

    phase_count = len(phases)

    def F(p, t, pair):
        return ('F', p, t % phase_count, *pair)

    def psi(p, t, state):
        return ('psi', p, t % phase_count, *state[0], *state[1])

    def chi(p, t, pair):
        return ('chi', p, t % phase_count, *pair)

    def local_difference(p, t, r):
        a, b, c = r
        return [(F(p, t, (b, c)), 1), (F(1-p, t, (a, b)), -1)]

    if alpha is None:
        add([(('alpha',), 1)], 0, ['slope_floor', 0])

    # One coherent edge advances the pair state (r,r') to (r',r'').
    for p in (0, 1):
        for t in phases:
            for state, following in edges:
                r, rp = state
                add(local_difference(p, t, r) +
                    [(psi(p, t+1, following), 1), (psi(p, t, state), -1)],
                    0, ['interior', p, t, list(r), list(rp), list(following[1])])

            # The smallest sound terminal language only needs the actual
            # one-update projection of a diagonal pair.  The two-update
            # coherence enters psi, where the old language resampled it.
            for pair in itertools.product((0, 1), repeat=2):
                b0, c0 = pair
                successors = sorted({(update(b0, a, z), update(c0, b0, a))
                                     for a, z in itertools.product((0, 1), repeat=2)})
                for following_pair in successors:
                    add([(F(p, t, pair), -1), (chi(p, t, pair), 1),
                         (chi(p, t+1, following_pair), -1)], 0,
                        ['terminal_flow', p, t, list(pair), list(following_pair)])

        # At the bottom, C is the emitted bit e_q.  g is the difference of
        # the two bottom endpoint corrections in Phi_q-Phi_(q-1).
        for state in states:
            r, rp = state
            terms = [(psi(p, 0, state), 1), (('b', p), -1),
                     (('g', p, r[1], r[2]), 1),
                     (('g', 1-p, r[0], r[1]), -1)]
            if alpha is None:
                terms.append((('alpha',), r[2]))
                bound = 1
            else:
                bound = 1 - alpha*r[2]
            add(terms, bound, ['bottom', p, list(r), list(rp)])

        # Exact final pair state S=(r_(q-3),r_(q-2)).
        if p == 0:
            tops = [((1, 1-b, b), (0, b, 1-b), (1, 1)) for b in (0, 1)]
            top_time = 1
        else:
            tops = [((u, 1-u, v), (1, 1, 1-v), (0, v))
                    for u, v in itertools.product((0, 1), repeat=2)]
            top_time = 0
        for r, rp, final_pair in tops:
            state = (r, rp)
            if state not in states:
                raise AssertionError('derived top state absent from coherent alphabet')
            add(local_difference(p, top_time, r) + local_difference(p, top_time+1, rp) +
                [(F(p, top_time+2, final_pair), 1),
                 (psi(p, top_time, state), -1), (('b', p), 1)],
                0, ['top', p, list(r), list(rp), list(final_pair)])

        # Terminal telescoping ends at the single final pair D(q-1),D(q).
        # Deduplicate final pairs: different top triples can share one endpoint.
        for final_pair in sorted({top[2] for top in tops}):
            for bottom_pair in itertools.product((0, 1), repeat=2):
                add([(chi(p, 0, bottom_pair), -1),
                     (('g', p, *bottom_pair), -1),
                     (F(p, top_time+2, final_pair), -1),
                     (chi(p, top_time+2, final_pair), 1)],
                    0, ['terminal_bound', p, list(bottom_pair), list(final_pair)])

    # q=2 initialization: alpha-2 + Phi_2 >= -1.
    for x in (0, 1):
        terms = [(F(0, 0, (x, 1-x)), 1), (F(0, 1, (1, 1)), 1),
                 (('g', 0, x, 1-x), 1)]
        if alpha is None:
            terms.append((('alpha',), 1))
            bound = 1
        else:
            bound = 1-alpha
        add(terms, bound, ['initial', x])
    return names, rows, rhs, labels


def check_farkas(rows, rhs, multipliers):
    if len(multipliers) != len(rows) or any(type(x) is not int or x < 0 for x in multipliers):
        raise ValueError('multipliers must be nonnegative integers, one per row')
    sums = [sum(m*r[j] for m, r in zip(multipliers, rows)) for j in range(len(rows[0]))]
    contradiction = sum(m*b for m, b in zip(multipliers, rhs))
    if any(sums) or contradiction <= 0:
        raise ValueError('invalid Farkas identity')
    return {'verified': True, 'nonzero_rows': sum(m > 0 for m in multipliers),
            'identity': f'0 >= {contradiction}', 'contradiction': contradiction}


def rational_integers(values):
    fractions = [Fraction(float(v)).limit_denominator(1_000_000) for v in values]
    scale = lcm(*(v.denominator for v in fractions))
    integers = [int(v*scale) for v in fractions]
    common = 0
    for value in integers:
        common = gcd(common, abs(value))
    return [v // (common or 1) for v in integers]


def solve(time_parity, alpha=8):
    import numpy as np
    from scipy.optimize import linprog
    names, rows, rhs, labels = inequality_system(time_parity, alpha)
    A, b = np.asarray(rows, dtype=float), np.asarray(rhs, dtype=float)
    answer = linprog(np.zeros(len(names)), A_ub=-A, b_ub=-b,
                     bounds=[(None, None)]*len(names), method='highs')
    report = {'time_parity': time_parity, 'alpha': 'variable' if alpha is None else alpha,
              'variables': len(names), 'inequalities': len(rows),
              'coherent_states': len(coherent_relation()[0]),
              'coherent_edges': len(coherent_relation()[1]),
              'optimizer_status': int(answer.status)}
    if answer.success:
        candidate = [Fraction(float(x)).limit_denominator(1_000_000) for x in answer.x]
        if not all(sum(Fraction(a)*x for a, x in zip(row, candidate)) >= bound
                   for row, bound in zip(rows, rhs)):
            raise RuntimeError('floating candidate failed exact rational check')
        report.update(outcome='rational_potential_candidate',
                      variable_names=[list(name) for name in names],
                      potential=[str(x) for x in candidate])
        return report
    dual = linprog(np.ones(len(rows)), A_eq=np.vstack((A.T, b)),
                   b_eq=np.r_[np.zeros(len(names)), 1.0], bounds=(0, None), method='highs')
    if not dual.success:
        report['outcome'] = 'unverified_solver_failure'
        return report
    multipliers = rational_integers(dual.x)
    checked = check_farkas(rows, rhs, multipliers)
    report.update(outcome='certificate_language_refuted', verification=checked,
                  farkas_multipliers=multipliers,
                  contributing_constraints=[{'label': label, 'multiplier': value}
                    for label, value in zip(labels, multipliers) if value])
    return report


def verify_report(report):
    for item in report['candidates']:
        _, rows, rhs, _ = inequality_system(item['time_parity'],
                                             None if item['alpha'] == 'variable' else item['alpha'])
        if item['outcome'] == 'certificate_language_refuted':
            check_farkas(rows, rhs, item['farkas_multipliers'])
        elif item['outcome'] == 'rational_potential_candidate':
            values = [Fraction(x) for x in item['potential']]
            if not all(sum(Fraction(a)*x for a, x in zip(row, values)) >= bound
                       for row, bound in zip(rows, rhs)):
                raise ValueError('invalid rational potential')
        else:
            raise ValueError('report contains no exact evidence')
    return {'verified_candidates': len(report['candidates']), 'arithmetic': 'rationals/integers only'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path)
    parser.add_argument('--verify', type=Path)
    args = parser.parse_args()
    if args.verify:
        print(json.dumps(verify_report(json.loads(args.verify.read_text()))))
        return
    candidates = [solve(parity, alpha) for parity in (False, True) for alpha in (8, None)]
    support_kinds = [{entry['label'][0] for entry in item['contributing_constraints']}
                     for item in candidates]
    report = {
        'experiment': 'two-update-predecessor-coherent-density-flux',
        'result': ('The predecessor-coherent signed density, terminal flux, and bottom-correction '
                   'language is infeasible with or without time parity, both at alpha=8 and for '
                   'every variable alpha>=0.'),
        'evidence': ('The 128 shared seven-bit words give exactly 20 adjacent-row states and 44 '
                     'coherent edges. Exact integer Farkas identities are 0>=2 (9 rows) without '
                     'time parity and 0>=6 (24 rows) with it.'),
        'gap': ('Two-update coherence removes the four known resampled walks, but it does not '
                'make this certificate language feasible. Every witness omits initialization and '
                'terminal-bound rows, and its alpha coefficients cancel on C=0 bottom rows, so '
                'relaxing the finite initial deficit or terminal constant cannot repair it.'),
        'next_implication': ('Audit the short coherent witness for the next missing correlation '
                             'before adding temporal memory; this result alone does not justify a '
                             'three-update language.'),
        'claim_limit': 'Tests one sufficient certificate language; it neither assumes nor proves reachability of every local state.',
        'candidates': candidates,
    }
    if any('initial' in kinds or 'terminal_bound' in kinds for kinds in support_kinds):
        raise AssertionError('endpoint-independent obstruction claim is not supported')
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps([{k: v for k, v in item.items()
                       if k not in ('farkas_multipliers', 'contributing_constraints',
                                    'potential', 'variable_names')}
                      for item in candidates], indent=2))


if __name__ == '__main__':
    main()
