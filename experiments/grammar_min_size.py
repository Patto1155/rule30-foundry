#!/usr/bin/env python
"""Smallest-grammar upper-bound curve g(n) for the Rule 30 center column.

Motivation
----------
This repo has now measured minimal-description curves over two model classes:
LFSRs (Experiment S, ``L(n) = n/2``) and DFAOs (``s*(n)``, certified
2026-08-30). Straight-line grammars are the natural third and the one closest
to Prize Problem 2, because a small straight-line grammar *is* a small program
that prints the prefix - which is what "a faster algorithm for the nth cell"
would have to be.

    g(n) = number of rules in the smallest straight-line program (SLP) in
           Chomsky normal form whose start symbol derives center bits 0..n-1

Every rule has the form ``A_i -> X Y`` with ``X, Y`` drawn from ``{0, 1}`` and
the nonterminals below ``i``, so an SLP with ``g`` rules is a fully explicit
finite object of size ``2g``.

**This is an upper-bound curve, and that is not a footnote.** Computing the
exactly smallest grammar is NP-hard, so ``g(n)`` here is what Re-Pair finds,
which is an upper bound on the true minimum. Every statement below is
therefore of the form "no *better than* this", and the comparison against the
random control is a comparison of two upper bounds produced by the same
deterministic algorithm - which is a fair comparison, but not the same claim
as ``s*(n)``, where the minima are exact.

Admission Rule, stated before running
-------------------------------------
(``docs/theory/finite-prefix-counting-bound.md``.) Rule ``i`` of a CNF SLP
chooses an ordered pair from ``{0,1} u {A_1..A_{i-1}}``, so

    |M(g)| = prod_{i=1..g} (i+1)^2 = ((g+1)!)^2
    log2|M(g)| = 2 * log2((g+1)!)

A negative over this class on an ``n``-bit prefix is vacuous unless
``log2|M(g)| >= n``. The threshold

    g_null(n) = min { g : 2*log2((g+1)!) >= n }

is therefore the size below which *no* grammar can fit almost any ``n``-bit
string, and a measured ``g(n)`` is only meaningful when it sits **above** it.
The artifact reports ``g_null(n)`` beside every measurement, and the run
refuses to describe a curve as informative where it does not clear the null.

Note what the counting bound does *not* say. It concerns the whole class of
SLPs; Re-Pair explores a heuristic slice of it. So ``g_null`` is a genuine
lower bound on the exact ``g*(n)`` for almost all strings, and the measured
Re-Pair value is an upper bound on ``g*(n)``. The true curve is between them.

Controls
--------
- **Positive**: Thue-Morse. It is generated by a length-doubling morphism, so
  its prefixes have grammars of size O(log n) and the curve must be far below
  the random band. If it is not, the measurement has no detection power and
  nothing else here means anything.
- **Null**: seeded random, 7 seeds, matching the band used for ``s*(n)``.
- **Analytic null**: ``g_null(n)`` above.

Usage
-----
    python experiments/grammar_min_size.py --out data/prize/grammar-curve.json
    python experiments/grammar_min_size.py --gate-only
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
import time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
for _p in (ROOT, ROOT / "experiments"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from dfao_min_states import sequence_bits, sha256_ascii  # noqa: E402
from prize_lab import bits_ascii, git_context  # noqa: E402

ARTIFACT_TYPE = "rule30.grammar_min_size_curve"
ARTIFACT_VERSION = 1

TERMINALS = 2  # symbols 0 and 1


def log(msg: str) -> None:
    print(msg, file=sys.stderr, flush=True)


# ---------------------------------------------------------------------------
# Re-Pair
# ---------------------------------------------------------------------------


def most_frequent_pair(seq: list[int]) -> tuple[tuple[int, int], int]:
    """Most frequent adjacent pair, counting every adjacent position.

    Overlapping occurrences of ``(a, a)`` are counted here and then resolved
    greedily at replacement time. That makes the count an over-estimate for
    runs, so the choice of pair can differ from a strictly non-overlapping
    Re-Pair. It cannot make the result unsound: whatever pair is chosen, the
    grammar produced still derives the input exactly, so its size is still an
    upper bound on g*(n). The same deterministic rule is applied to the center
    column and to every control, which is what the comparison needs.
    """
    counts: dict[tuple[int, int], int] = defaultdict(int)
    for i in range(len(seq) - 1):
        counts[(seq[i], seq[i + 1])] += 1
    if not counts:
        return (0, 0), 0
    # Tie-break on the pair itself so the run is deterministic.
    best = max(counts.items(), key=lambda kv: (kv[1], -kv[0][0], -kv[0][1]))
    return best[0], best[1]


def replace_pair(seq: list[int], pair: tuple[int, int], symbol: int) -> list[int]:
    """Replace non-overlapping left-to-right occurrences of ``pair``."""
    a, b = pair
    out: list[int] = []
    i, n = 0, len(seq)
    while i < n:
        if i + 1 < n and seq[i] == a and seq[i + 1] == b:
            out.append(symbol)
            i += 2
        else:
            out.append(seq[i])
            i += 1
    return out


def expand(rules: list[tuple[int, int]], seq: list[int]) -> list[int]:
    """Expand an SLP back to its string, iteratively (no recursion limit)."""
    out: list[int] = []
    stack = list(reversed(seq))
    while stack:
        sym = stack.pop()
        if sym < TERMINALS:
            out.append(sym)
        else:
            a, b = rules[sym - TERMINALS]
            stack.append(b)
            stack.append(a)
    return out


def repair_with_check(bits: list[int]) -> dict:
    """Re-Pair, plus proof that the grammar actually derives the input.

    A grammar that does not reproduce its own string would make every size in
    this experiment meaningless, so it is checked rather than assumed.
    """
    seq = list(bits)
    rules: list[tuple[int, int]] = []
    next_symbol = TERMINALS
    while True:
        pair, count = most_frequent_pair(seq)
        if count < 2:
            break
        seq = replace_pair(seq, pair, next_symbol)
        rules.append(pair)
        next_symbol += 1

    reproduced = expand(rules, seq)
    if reproduced != list(bits):
        raise AssertionError(
            f"grammar does not derive its input: {len(reproduced)} vs {len(bits)} bits")

    start_rules = max(0, len(seq) - 1)
    return {
        "g_rules": len(rules) + start_rules,
        "repair_rules": len(rules),
        "start_sequence_len": len(seq),
        "start_binarisation_rules": start_rules,
        "total_rhs_symbols": 2 * len(rules) + len(seq),
        "derivation_verified": True,
    }


# ---------------------------------------------------------------------------
# counting null
# ---------------------------------------------------------------------------


def log2_slp_class(g: int) -> float:
    """log2 of the number of CNF SLPs with g rules over a binary alphabet."""
    return 2.0 * (math.lgamma(g + 2) / math.log(2.0))


def g_null(n: int) -> int:
    """Smallest rule count whose class is large enough to fit n bits at all."""
    g = 1
    while log2_slp_class(g) < n:
        g += 1
    return g


# ---------------------------------------------------------------------------
# gate
# ---------------------------------------------------------------------------


def gate() -> dict:
    """Detection-power checks. Nothing is measured until these pass."""
    checks: list[dict] = []

    def record(name: str, ok: bool, detail) -> None:
        checks.append({"check": name, "passed": bool(ok), "detail": detail})
        log(f"  [{'PASS' if ok else 'FAIL'}] {name}  ({detail})")

    # 1. The grammar must reproduce its input, on every sequence we will use.
    for name in ("center", "thue-morse", "random"):
        bits = sequence_bits(name, 512, seed=30)
        res = repair_with_check(bits)
        record(f"{name} n=512 grammar derives its own input",
               res["derivation_verified"], f"g={res['g_rules']}")

    # 2. A constant string must be near-logarithmic, not linear.
    const = repair_with_check([1] * 4096)
    record("all-ones n=4096 compresses to O(log n) rules",
           const["g_rules"] < 40, f"g={const['g_rules']}")

    # 3. Positive control: Thue-Morse must land far below random.
    tm = repair_with_check(sequence_bits("thue-morse", 4096))["g_rules"]
    rnd = repair_with_check(sequence_bits("random", 4096, seed=30))["g_rules"]
    record("thue-morse n=4096 is far below random",
           tm < rnd / 3, f"thue-morse {tm} vs random {rnd}")

    # 4. The center prefix must agree with the hash-anchored golden reference.
    golden = ROOT / "data" / "golden" / "center_col_golden_1M.bin"
    if golden.exists():
        import numpy as np
        raw = np.fromfile(golden, dtype=np.uint8, count=1024)
        # golden files are MSB-first by deliberate, documented exception
        ref = np.unpackbits(raw, bitorder="big")[:4096].tolist()
        record("center prefix matches the golden reference over 4096 bits",
               ref == list(sequence_bits("center", 4096)), "4096 bits")
    else:
        record("golden reference present", False, "absent; cannot cross-check")

    # 5. The measurement must sit in the informative regime somewhere.
    n = 4096
    record("random g(n) clears the counting null at n=4096",
           rnd > g_null(n), f"g={rnd} vs g_null={g_null(n)}")

    passed = all(c["passed"] for c in checks)
    log(f"gate {'PASSED' if passed else 'FAILED'}")
    return {"passed": passed, "checks": checks}


# ---------------------------------------------------------------------------
# sweep
# ---------------------------------------------------------------------------


def run_curve(n_values: list[int], seeds: list[int]) -> list[dict]:
    rows: list[dict] = []
    for n in n_values:
        null = g_null(n)
        entry = {"n": n, "g_null": null,
                 "log2_class_at_null": round(log2_slp_class(null), 2)}

        t0 = time.perf_counter()
        center = repair_with_check(sequence_bits("center", n))
        entry["center"] = center
        entry["sha256_bits_ascii"] = sha256_ascii(
            bits_ascii(sequence_bits("center", n)))

        tm = repair_with_check(sequence_bits("thue-morse", n))
        entry["thue_morse"] = tm

        band = []
        for seed in seeds:
            band.append(repair_with_check(
                sequence_bits("random", n, seed=seed))["g_rules"])
        band.sort()
        entry["random_band"] = band
        entry["random_min"] = band[0]
        entry["random_max"] = band[-1]
        entry["random_median"] = band[len(band) // 2]

        g = center["g_rules"]
        entry["center_inside_band"] = band[0] <= g <= band[-1]
        entry["center_below_band"] = g < band[0]
        entry["center_clears_counting_null"] = g > null
        entry["elapsed_s"] = round(time.perf_counter() - t0, 3)

        log(f"  n={n:6d}  center {g:5d}  random [{band[0]},{band[-1]}]  "
            f"thue-morse {tm['g_rules']:4d}  g_null {null:4d}  "
            f"{'inside' if entry['center_inside_band'] else ('BELOW' if entry['center_below_band'] else 'above')}"
            f"  ({entry['elapsed_s']:.1f}s)")
        rows.append(entry)
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-values", default="64,128,256,512,1024,2048,4096,8192")
    ap.add_argument("--seeds", default="30,31,32,33,34,35,36")
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--gate-only", action="store_true")
    args = ap.parse_args()

    log("gate:")
    gate_result = gate()
    if not gate_result["passed"]:
        log("gate failed; refusing to measure")
        return 1
    if args.gate_only:
        return 0

    n_values = [int(x) for x in args.n_values.split(",")]
    seeds = [int(x) for x in args.seeds.split(",")]

    log(f"\ncurve over n = {n_values}, {len(seeds)} random seeds:")
    started = time.time()
    rows = run_curve(n_values, seeds)
    elapsed = time.time() - started

    exact_rows = [r for r in rows if r["center_clears_counting_null"]]
    artifact = {
        "artifact_type": ARTIFACT_TYPE,
        "artifact_version": ARTIFACT_VERSION,
        "claim_level": "Robust observation (upper-bound curve; exact g*(n) is NP-hard)",
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "elapsed_s": round(elapsed, 3),
        "question": (
            "How does the smallest-grammar size of the Rule 30 center-column "
            "prefix grow with n, relative to a matched random control?"),
        "method": {
            "algorithm": "Re-Pair, then the residual start sequence binarised "
                         "into a left-deep chain so the object is a CNF SLP",
            "upper_bound_only": (
                "Computing the exactly smallest grammar is NP-hard. Every "
                "g(n) here is what Re-Pair found, an UPPER bound on g*(n). "
                "The comparison against the control is between two upper "
                "bounds from the same deterministic algorithm."),
            "size_measure": "number of CNF rules (2 symbols per RHS)",
            "derivation_checked": (
                "every grammar is expanded and compared against its input"),
        },
        "counting_null": {
            "formula": "|M(g)| = ((g+1)!)^2, so log2|M(g)| = 2*log2((g+1)!)",
            "meaning": (
                "g_null(n) is the smallest rule count whose class is large "
                "enough to express an arbitrary n-bit string at all. A "
                "measured g(n) at or below g_null(n) would be uninformative "
                "by counting."),
            "reference": "docs/theory/finite-prefix-counting-bound.md",
            "note": (
                "g_null is a lower bound on the exact g*(n) for almost all "
                "strings; Re-Pair gives an upper bound. The true curve lies "
                "between them."),
        },
        "gate": gate_result,
        "params": {"n_values": n_values, "seeds": seeds},
        "summary": {
            "rows": len(rows),
            "rows_clearing_counting_null": len(exact_rows),
            "center_inside_band": sum(1 for r in rows if r["center_inside_band"]),
            "center_below_band": sum(1 for r in rows if r["center_below_band"]),
            "center_above_band": sum(
                1 for r in rows
                if not r["center_inside_band"] and not r["center_below_band"]),
        },
        "git": git_context(),
        "results": rows,
    }

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(artifact, indent=2) + "\n",
                            encoding="utf-8", newline="")
        log(f"\nwrote {args.out}")
    else:
        print(json.dumps(artifact, indent=2))

    s = artifact["summary"]
    log(f"center inside the random band at {s['center_inside_band']}/{s['rows']} "
        f"prefix lengths, below at {s['center_below_band']}, "
        f"above at {s['center_above_band']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
