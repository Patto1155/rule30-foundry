#!/usr/bin/env python3
"""Explore a finite grammar of alternating-trace claims with exact falsifiers.

Jev chooses which already-formed claim to test. No model output is interpreted
as a theorem, witness, or command. See docs/JEV_LATERAL_SEARCH.md.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import itertools
import json
import os
import random
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments.rule30_open_utils import step_naive_open  # noqa: E402

ENDPOINTS = {
    "typesafe": ("https://api.typesafe.ai/v1/systemone", "jev-latest"),
    "openrouter": ("https://openrouter.ai/api/alpha/decisions", "~typesafe/jev-latest"),
}
OFFSETS = (-3, -2, -1, 1, 2, 3)
LITERALS = tuple((offset, bit) for offset in OFFSETS for bit in (0, 1))


def save(path: Path, data: object) -> None:
    path.write_text(json.dumps(data, indent=2, sort_keys=True, allow_nan=False) + "\n",
                    encoding="utf-8")


def card_id(card: dict) -> str:
    def offset_name(offset: int) -> str:
        return ("m" if offset < 0 else "p") + str(abs(offset))
    antecedent = "u" if not card["premises"] else "_".join(
        f"{offset_name(offset)}b{bit}" for offset, bit in card["premises"])
    return (f"c{card['phase']}-{antecedent}-z{offset_name(card['target'])}"
            f"t{card['lag']}b{card['value']}")


def make_cards(max_premises: int = 2) -> list[dict]:
    """Finite, frozen grammar; no text is generated by Jev."""
    if max_premises not in (0, 1, 2):
        raise ValueError("max_premises must be 0, 1, or 2")
    premise_sets = [()]
    if max_premises >= 1:
        premise_sets.extend((literal,) for literal in LITERALS)
    if max_premises >= 2:
        premise_sets.extend(
            pair for pair in itertools.combinations(LITERALS, 2)
            if pair[0][0] != pair[1][0])
    cards = []
    for phase in (0, 1):
        for premises in premise_sets:
            for target in OFFSETS:
                for lag in (0, 1, 2):
                    for value in (0, 1):
                        if lag == 0 and any(target == offset for offset, _ in premises):
                            continue  # Premise implies its own conclusion.
                        card = {"phase": phase, "premises": premises, "target": target,
                                "lag": lag, "value": value}
                        card["id"] = card_id(card)
                        cards.append(card)
    return cards


def describe(card: dict) -> str:
    premise = "".join(f" and a(t,{offset})={bit}"
                      for offset, bit in card["premises"])
    return (f"Within an alternating centre block, c(t)={card['phase']}"
            f"{premise} implies a(t+{card['lag']},{card['target']})"
            f"={card['value']}.")


def exact_rows(radius: int, steps: int) -> np.ndarray:
    """All nonzero finite rows, zero padded past the entire light cone."""
    if not 1 <= radius <= 7 or not 6 <= steps <= 40:
        raise ValueError("radius must be 1..7 and steps 6..40")
    span = 2 * radius + 1
    width = 2 * (radius + steps + 4) + 1
    center = width // 2
    indices = np.arange(1, 1 << span, dtype=np.uint32)
    bits = ((indices[:, None] >> np.arange(span, dtype=np.uint32)) & 1).astype(np.uint8)
    rows = np.zeros((len(indices), width), dtype=np.uint8)
    rows[:, center - radius:center + radius + 1] = bits
    cols = np.empty((len(indices), steps + 1, 7), dtype=np.uint8)
    for t in range(steps + 1):
        cols[:, t, :] = rows[:, center - 3:center + 4]
        if t < steps:
            if t < 2:  # Independent stepper and spatial-orientation control.
                for i in (0, len(indices) // 2, len(indices) - 1):
                    assert np.array_equal(step_naive_open(rows[i]),
                                          vector_step(rows[i:i + 1])[0])
            rows = vector_step(rows)
    return cols


def vector_step(rows: np.ndarray) -> np.ndarray:
    left = np.zeros_like(rows)
    left[:, 1:] = rows[:, :-1]
    right = np.zeros_like(rows)
    right[:, :-1] = rows[:, 1:]
    return left ^ (rows | right)


def evaluate(card: dict, cols: np.ndarray, radius: int, window: int) -> dict:
    """Find a witness, or exhaust the whole light cone of this local claim."""
    if not 3 <= window <= cols.shape[1]:
        raise ValueError("invalid alternating window")
    c = cols[:, :, 3]
    support = violations = time_zero_support = time_zero_violations = 0
    witness = None
    for t in range(cols.shape[1] - window + 1):
        mask = c[:, t] == card["phase"]
        for k in range(window - 1):
            mask &= c[:, t + k] != c[:, t + k + 1]
        for offset, bit in card["premises"]:
            mask &= cols[:, t, offset + 3] == bit
        bad = mask & (cols[:, t + card["lag"], card["target"] + 3] != card["value"])
        support += int(mask.sum())
        violations += int(bad.sum())
        if t == 0:
            time_zero_support = int(mask.sum())
            time_zero_violations = int(bad.sum())
        if witness is None and bad.any():
            witness = {"initial_bits_integer": int(np.flatnonzero(bad)[0] + 1),
                       "radius": radius, "time": t,
                       "centre_window": c[np.flatnonzero(bad)[0], t:t + window].tolist()}
    needed_radius = max(window - 1, abs(card["target"]) + card["lag"],
                        max((abs(offset) for offset, _ in card["premises"]), default=0))
    complete = radius >= needed_radius and time_zero_support > 0
    return {"support": support, "violations": violations,
            "time_zero_support": time_zero_support,
            "time_zero_violations": time_zero_violations,
            "required_proof_radius": needed_radius,
            "verdict": "FALSIFIED" if witness else
                       ("PROVED_LOCAL_EXHAUSTIVE" if complete else
                        ("SURVIVED_BOUNDED" if support else "UNINFORMATIVE")),
            "witness": witness}


def screen_one(card: dict, provider: str, timeout: float) -> dict:
    """One distinct candidate, several atomic judgments evaluated in parallel."""
    if provider == "auto":
        provider = "openrouter" if os.environ.get("OPENROUTER_API_KEY") else "typesafe"
    key = os.environ.get("OPENROUTER_API_KEY" if provider == "openrouter"
                         else "TYPESAFE_API_KEY")
    if not key:
        raise ValueError("Jev policy needs an API key in the environment")
    endpoint, model = ENDPOINTS[provider]
    request = {"model": model, "state": {
        "research_goal": "Find a symbolic constraint useful for classifying the infinite alternating-trace fiber of Rule 30 and excluding finite support.",
        "candidate": describe(card),
        "finite_evidence": card["preflight"],
        "known": [
            "This claim survived only a finite exhaustive check; it is not a theorem.",
            "D1: under alternation, c(t)=1 implies a(t,-1)=1.",
            "D2: under alternation, c(t)=0 implies a(t,-1)=1 XOR a(t,1).",
            "D3: under alternation, column -2 is a phase-dependent copy of column +1.",
            "A useful survivor must ultimately connect infinite alternation and finite spatial support."],
        "instruction": "Judge research allocation only. Probabilities are not mathematical evidence."},
        "questions": {
            "direct_rule": {"type": "noul",
                "instructions": "Is this probably just a direct one- or two-step substitution of the Rule 30 recurrence or the listed identities?",
                "criteria": {"true": "Likely routine algebra already implicit in the known identities",
                             "false": "Appears to add a nontrivial constraint"}},
            "proof_value": {"type": "score",
                "instructions": "How useful would a symbolic proof of this exact claim be for classifying the alternating-trace fiber?",
                "criteria": ["No useful bridge", "Minor simplification", "Useful intermediate lemma",
                             "Strong forced-tail ingredient", "Could nearly close finite-support exclusion"]},
            "next_move": {"type": "choice",
                "instructions": "What should the frontier reasoning agent do with this claim next?",
                "criteria": {"derive": "Attempt a symbolic derivation now",
                             "strengthen": "Search for a stronger nearby statement",
                             "combine": "Combine it with another phase or depth constraint",
                             "falsify-deeper": "Spend more exact compute seeking a deeper counterexample",
                             "park": "Do not spend frontier-agent attention"}},
            "route": {"type": "choice",
                "instructions": "Which proof route would this exact claim most naturally support?",
                "criteria": {"forced-tail": "Show the unique compatible left half has infinite support",
                             "constant-column": "Force another column eventually constant",
                             "mirror": "Express the left half using the right half",
                             "two-step": "Expose structure under the two-step Rule 30 map",
                             "none": "No credible route"}}}}
    body = json.dumps(request).encode("utf-8")
    http = urllib.request.Request(endpoint, body, headers={
        "Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(http, timeout=timeout) as response:
                answer = json.load(response)
            break
        except urllib.error.HTTPError as exc:
            if exc.code not in (429, 529) or attempt == 4:
                raise
            time.sleep(0.25 * (2 ** attempt))
        except (urllib.error.URLError, TimeoutError):
            if attempt == 4:
                raise
            time.sleep(0.25 * (2 ** attempt))
    answers = answer.get("answers", {})
    if set(answers) != {"direct_rule", "proof_value", "next_move", "route"}:
        raise ValueError("Jev returned the wrong screening schema")
    direct = answers["direct_rule"].get("noul")
    score = answers["proof_value"].get("score")
    move = answers["next_move"].get("choice")
    route = answers["route"].get("choice")
    if (type(direct) not in (int, float) or not 0 <= direct <= 1 or
        type(score) not in (int, float) or not 0 <= score <= 4 or
        move not in {"derive", "strengthen", "combine", "falsify-deeper", "park"} or
        route not in {"forced-tail", "constant-column", "mirror", "two-step", "none"}):
        raise ValueError("Jev returned invalid screening values")
    tokens = answer.get("usage", {}).get("input_tokens")
    if type(tokens) is not int or tokens < 0:
        raise ValueError("missing Jev token usage")
    # A transparent attention score, not a truth probability.
    move_weight = {"derive": 1.0, "combine": 0.9, "strengthen": 0.75,
                   "falsify-deeper": 0.55, "park": 0.0}[move]
    route_weight = 0.45 if route == "none" else 1.0
    priority = float(score) * (1.0 - 0.7 * float(direct)) * move_weight * route_weight
    return {"id": card["id"], "claim": describe(card), "direct_rule": direct,
            "proof_value": score, "next_move": move, "route": route,
            "attention_priority": round(priority, 6), "input_tokens": tokens,
            "answers": answers}


def screen_jev(cards: list[dict], provider: str, timeout: float,
               concurrency: int) -> tuple[list[dict], list[dict]]:
    """Screen distinct claims concurrently; no repeated votes on one claim."""
    results = []
    failures = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=concurrency) as executor:
        futures = {executor.submit(screen_one, card, provider, timeout): card["id"]
                   for card in cards}
        for future in concurrent.futures.as_completed(futures):
            try:
                results.append(future.result())
            except Exception as exc:
                failures.append({"id": futures[future], "error": str(exc)})
    return (sorted(results, key=lambda x: (-x["attention_priority"], x["id"])),
            sorted(failures, key=lambda x: x["id"]))


def run(args: argparse.Namespace) -> dict:
    if not 3 <= args.window <= args.steps + 1 or not 1 <= args.preflight_radius < args.radius <= 7:
        raise ValueError("invalid window/radius limits")
    if not 1 <= args.max_cards <= 1000 or not 1 <= args.max_tests <= args.max_cards:
        raise ValueError("max-cards must be 1..1000 and max-tests <= max-cards")
    if not 2 <= args.batch <= 20 or not 1 <= args.concurrency <= 32 or args.timeout <= 0:
        raise ValueError("invalid batch/timeout")
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    preflight = exact_rows(args.preflight_radius, args.steps)
    # Independent sanity controls; any failure prevents selection.
    true_control = {"phase": 1, "premises": (),
                    "target": -1, "lag": 0, "value": 1}
    false_control = {**true_control, "value": 0}
    positive = evaluate(true_control, preflight, args.preflight_radius, args.window)
    negative = evaluate(false_control, preflight, args.preflight_radius, args.window)
    if (positive["support"] == 0 or positive["violations"] or
        negative["violations"] == 0):
        raise ValueError("alternating-trace controls did not calibrate")
    cards = make_cards(args.max_premises)
    survivors = []
    for card in cards:
        verdict = evaluate(card, preflight, args.preflight_radius, args.window)
        if verdict["verdict"] in ("SURVIVED_BOUNDED", "PROVED_LOCAL_EXHAUSTIVE"):
            card["preflight"] = verdict
            survivors.append(card)
    # Frozen independently of Jev. All policies receive these same exact cards.
    survivors.sort(key=lambda c: (len(c["premises"]), -c["preflight"]["support"],
                                  abs(c["target"]), c["lag"], c["id"]))
    # Preserve the frozen ordering but sample across its whole range. Taking a
    # prefix would fill a 200-card campaign mostly with unconditional and
    # one-premise identities, silently defeating the point of expanding the
    # grammar to two simultaneous constraints.
    if len(survivors) > args.max_cards:
        last = len(survivors) - 1
        indices = [round(i * last / (args.max_cards - 1))
                   for i in range(args.max_cards)] if args.max_cards > 1 else [0]
        survivors = [survivors[i] for i in indices]
    if not survivors:
        raise ValueError("no supported candidates survived preflight")
    pool_hash = hashlib.sha256(json.dumps(survivors, sort_keys=True).encode()).hexdigest()
    save(out / "pool.json", {"grammar_size": len(cards), "survived_preflight": len(survivors),
                             "pool_sha256": pool_hash, "cards": survivors,
                             "controls": {"positive": positive, "negative": negative}})
    target = exact_rows(args.radius, args.steps)
    rng = random.Random(args.seed)
    pending = survivors.copy()
    history = []
    input_tokens = 0
    started = time.monotonic()
    stop = "budget"
    screening = []
    screening_failures = []
    if args.policy == "jev":
        screening, screening_failures = screen_jev(
            pending, args.jev_provider, args.timeout, args.concurrency)
        if len(screening) < args.max_tests:
            raise ValueError(f"only {len(screening)} Jev screenings succeeded; "
                             f"need {args.max_tests}")
        by_id = {card["id"]: card for card in pending}
        pending = [by_id[item["id"]] for item in screening]
        input_tokens = sum(item["input_tokens"] for item in screening)
        save(out / "jev_screening.json", screening)
        save(out / "jev_failures.json", screening_failures)
    elif args.policy == "random":
        rng.shuffle(pending)
    while pending and len(history) < args.max_tests:
        offered = pending[:args.batch]
        if args.policy == "fixed":
            choice, meta = offered[0]["id"], {}
        elif args.policy == "random":
            choice, meta = offered[0]["id"], {}
        else:
            # Screening already produced a frozen order using one distinct call
            # per candidate; do not turn repeated voting into fake independence.
            choice, meta = offered[0]["id"], {}
        if choice == "return-to-lead":
            stop = "return-to-lead"
            break
        if choice not in {c["id"] for c in offered}:
            raise ValueError("selector chose a card not offered")
        card = next(c for c in pending if c["id"] == choice)
        pending.remove(card)
        result = evaluate(card, target, args.radius, args.window)
        history.append({"step": len(history) + 1, "chosen": choice,
                        "claim": describe(card), "offered": [c["id"] for c in offered],
                        "preflight_support": card["preflight"]["support"],
                        "result": result,
                        "jev_input_tokens": meta.get("input_tokens", 0)})
    if not pending:
        stop = "pool-exhausted"
    summary = {"policy": args.policy, "seed": args.seed, "pool_sha256": pool_hash,
               "grammar_size": len(cards), "pool_size": len(survivors),
               "preflight_radius": args.preflight_radius, "test_radius": args.radius,
               "steps": args.steps, "window": args.window, "stop": stop,
               "tests": len(history), "falsified": sum(x["result"]["violations"] > 0 for x in history),
               "proved_local": sum(x["result"]["verdict"] == "PROVED_LOCAL_EXHAUSTIVE"
                                   for x in history),
               "bounded_survivors": sum(x["result"]["verdict"] == "SURVIVED_BOUNDED"
                                        for x in history),
               "jev_calls": len(screening), "jev_calls_succeeded": len(screening),
               "jev_calls_failed": len(screening_failures),
               "jev_input_tokens": input_tokens,
               "elapsed_s": round(time.monotonic() - started, 3),
               "claim_limit": "PROVED_LOCAL_EXHAUSTIVE is a theorem about the stated "
                              "finite-window implication because its entire light cone was "
                              "enumerated. It is not an infinite alternating-fiber theorem "
                              "or a prize result; SURVIVED_BOUNDED remains only finite evidence."}
    if stop == "pool-exhausted":
        by_id = {card["id"]: card for card in survivors}
        proved_ids = {item["chosen"] for item in history
                      if item["result"]["verdict"] == "PROVED_LOCAL_EXHAUSTIVE"}
        proved_keys = {
            (by_id[i]["phase"], tuple(tuple(p) for p in by_id[i]["premises"]),
             by_id[i]["target"], by_id[i]["lag"], by_id[i]["value"])
            for i in proved_ids}
        irredundant = []
        for i in proved_ids:
            card = by_id[i]
            premises = tuple(tuple(p) for p in card["premises"])
            implied_by_subset = any(
                (card["phase"], subset, card["target"], card["lag"], card["value"])
                in proved_keys
                for size in range(len(premises))
                for subset in itertools.combinations(premises, size))
            if not implied_by_subset:
                irredundant.append(i)
        summary["irredundant_local_theorems"] = len(irredundant)
        summary["irredundant_by_premise_count"] = {
            str(size): sum(len(by_id[i]["premises"]) == size for i in irredundant)
            for size in range(args.max_premises + 1)}
    save(out / "trace.json", history)
    save(out / "summary.json", summary)
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--policy", choices=("fixed", "random", "jev"), default="fixed")
    parser.add_argument("--jev-provider", choices=("auto", "openrouter", "typesafe"), default="auto")
    parser.add_argument("--preflight-radius", type=int, default=2)
    parser.add_argument("--radius", type=int, default=4)
    parser.add_argument("--window", type=int, default=5)
    parser.add_argument("--steps", type=int, default=12)
    parser.add_argument("--max-cards", type=int, default=48)
    parser.add_argument("--max-tests", type=int, default=12)
    parser.add_argument("--batch", type=int, default=8)
    parser.add_argument("--max-premises", type=int, choices=(0, 1, 2), default=2)
    parser.add_argument("--concurrency", type=int, default=12)
    parser.add_argument("--seed", type=int, default=30)
    parser.add_argument("--timeout", type=float, default=30)
    args = parser.parse_args()
    try:
        print(json.dumps(run(args), indent=2))
    except (ValueError, OSError, KeyError) as exc:
        print(f"jev_conjecture_search: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
